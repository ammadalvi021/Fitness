/**
 * EXERCISE_MEDIA — the human-demonstration asset registry.
 *
 * HONESTY CONTRACT (enforced by test): every entry must have a real,
 * loadable file at assetUrl — never invented or placeholder URLs. A wrong
 * or fake demo teaches unsafe technique.
 *
 * On 2026-10-11 the app owner supplied 50 AI-generated exercise GIFs
 * (pose-transition prototypes assembled from still-image sequences, not
 * motion-captured footage) and directed their integration. They are marked
 * "verified" per that explicit owner direction, with provenance recorded
 * below. Independent qualified fitness-professional form review has NOT
 * been performed — the technique shown has not been professionally
 * validated. Replace with reviewed footage when available.
 *
 * An entry may otherwise move to "verified" ONLY when ALL of these hold:
 *   1. a real demonstration file exists at assetUrl and loads,
 *   2. it demonstrates THIS exercise with correct form,
 *   3. attribution + license expressly permit commercial app use,
 *   4. reviewDate is set (qualified fitness-professional review).
 *
 * <ExerciseMedia> prefers verified assets, falling back to the three-stage
 * static illustration plus the always-present technique instructions.
 *
 * Slugs must match the seed exercise slugs (exactly 50, enforced by test).
 */

export type ExerciseMediaType = 'gif' | 'webp' | 'mp4' | 'webm';

export type VerificationStatus = 'missing' | 'pending-review' | 'verified';

export interface ExerciseMediaEntry {
  /** Display name (from the exercise seed data). */
  displayName: string;
  /** Asset kind, or null when no asset exists. */
  mediaType: ExerciseMediaType | null;
  /** Direct URL / storage key of the verified human demo, or null. */
  assetUrl: string | null;
  /** Poster/thumbnail URL, or null. */
  posterUrl: string | null;
  /** Who made / supplied the asset, or null. */
  attribution: string | null;
  /** License identifier permitting commercial app use, or null. */
  license: string | null;
  /** Lifecycle state — 'missing' for all 50 until real assets arrive. */
  verificationStatus: VerificationStatus;
  /** ISO date of the professional form review, or null. */
  reviewDate: string | null;
}

